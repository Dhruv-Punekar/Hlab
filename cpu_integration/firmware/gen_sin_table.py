#!/usr/bin/env python3
"""Writes sin_table.h: quarter-wave sine, 257 entries, Q16.16 (65536 = 1.0).
Angle unit used by the firmware: 1024 per full turn, so entry i is
sin(i * 2*pi / 1024) for i = 0..256 (0 .. 90 degrees)."""
import math
vals = [round(65536 * math.sin(i * 2 * math.pi / 1024)) for i in range(257)]
with open("sin_table.h", "w") as f:
    f.write("/* generated by gen_sin_table.py - do not edit */\n")
    f.write("/* quarter-wave sine, Q16.16, angle unit = 1/1024 turn */\n")
    f.write("static const int32_t SIN_Q16[257] = {\n")
    for i in range(0, 257, 8):
        f.write("    " + ", ".join(str(v) for v in vals[i:i+8]) + ",\n")
    f.write("};\n")
