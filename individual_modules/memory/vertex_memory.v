`timescale 1ns / 1ps

// ============================================================================
// Module: vertex_memory
// Purpose: Stores the 144-bit vertices of the 3D model. 
// Implementation: Uses Block RAM (BRAM) so it doesn't consume logic resources.
// ============================================================================
module vertex_memory #(
    // DEPTH = Number of vertices to store. 36 vertices = 12 triangles (1 cube).
    parameter DEPTH = 64, 
    parameter WIDTH = 144
)(
    input wire clk,
    input wire en,             // Read Enable (High when FSM wants data)
    input wire we,             // Write Enable (For future UART updates)
    input wire [$clog2(DEPTH)-1:0] addr, // Memory Address
    input wire [WIDTH-1:0] data_in,      // Data to write (Future)
    
    output reg [WIDTH-1:0] data_out      // Read Data (Output to FSM)
);

    // This creates an array of 64 slots, where each slot is 144 bits wide.
    // Vivado automatically infers this as a BRAM block.
    reg [WIDTH-1:0] ram [0:DEPTH-1];

    // ========================================================================
    // INITIALIZATION
    // ========================================================================
    // $readmemh reads the Hex file generated by Python at compile-time and 
    // burns it directly into the FPGA's bitstream.
    initial begin
        $readmemh("vertices.mem", ram);
    end

    // ========================================================================
    // SYNCHRONOUS MEMORY ACCESS
    // ========================================================================
    always @(posedge clk) begin
        if (en) begin
            // Write operation (Ignored for Phase 1 since we=0)
            if (we) begin
                ram[addr] <= data_in; 
            end
            // Read operation (Outputs the data at the requested address)
            data_out <= ram[addr];
        end
    end

endmodule
