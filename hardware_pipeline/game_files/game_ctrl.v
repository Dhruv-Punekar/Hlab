`timescale 1ns / 1ps
// ============================================================================
// Module: game_ctrl                                       (NEW, game feature)
//   Holds the "game state" of the cube and updates it once per rendered
//   frame (tick pulse), from the debounced buttons, the switches and the
//   accelerometer.
//
//   State                     unit                         reset value
//   yaw, pitch               1/1024 turn (10 bits, wraps)  100 (35 deg), 71 (25 deg)
//   tx, ty                   Q8.8 world units              0
//   cam_dist                 Q8.8 world units              6.0 (1536)
//   (these defaults give exactly the picture of the project's matrix.mem)
//
//   Controls (see the operating manual):
//     BTNC                   reset view (held = stays at the start pose)
//     SW0                    auto-spin (yaw keeps turning)
//     SW1 = 0, SW2 = 0       rotate mode: L/R turn left/right, U/D tip up/down
//     SW1 = 1                move mode:   L/R/U/D slide the cube
//     SW2 = 1                zoom mode:   U = closer, D = farther, L/R still rotate
//                            (SW2 has priority over SW1)
//   Move limits depend on the zoom distance so the whole cube always stays on
//   the screen (farther away = more room to move).
//     SW4:SW3                speed  00 = x1, 01 = x2, 10 = x4, 11 = x8
//     SW15                   tilt control on (accelerometer adds pitch / roll)
//     SW12                   tilt: swap the board X and Y axes
//     SW13 / SW14            tilt: reverse roll / reverse pitch direction
//   Speeds at 60 frames/s:   rotate  x1 = 21 deg/s ... x8 = 169 deg/s
//                            move    x1 = 0.47 units/s, zoom x1 = 0.94 units/s
// ============================================================================
module game_ctrl #(
    parameter [9:0]         YAW0      = 10'd100,
    parameter [9:0]         PITCH0    = 10'd71,
    parameter signed [15:0] DIST0     = 16'sd1536,   // 6.0
    parameter signed [15:0] DIST_MIN  = 16'sd1152,   // 4.5  (closest)
    parameter signed [15:0] DIST_MAX  = 16'sd3072    // 12.0 (farthest)
)(
    input  wire               clk,
    input  wire               rst_n,
    input  wire               tick,          // one pulse per frame
    input  wire               btn_c, btn_u, btn_l, btn_r, btn_d,
    input  wire       [15:0]  sw,
    input  wire signed [11:0] acc_x,
    input  wire signed [11:0] acc_y,
    input  wire               acc_valid,     // new accelerometer sample

    output reg         [9:0]  yaw,
    output reg         [9:0]  pitch,         // button pitch (without tilt)
    output reg         [9:0]  pitch_eff,     // pitch + tilt  -> matrix_builder
    output reg         [9:0]  roll_eff,      // tilt roll     -> matrix_builder
    output reg signed  [15:0] tx,
    output reg signed  [15:0] ty,
    output reg signed  [15:0] cam_dist,
    output reg                at_limit,      // last update hit a move/zoom limit
    output reg signed  [9:0]  tilt_pitch,    // filtered tilt angles (debug / LEDs)
    output reg signed  [9:0]  tilt_roll
);
    wire auto_spin = sw[0];
    wire move_mode = sw[1] & ~sw[2];
    wire zoom_mode = sw[2];
    wire tilt_on   = sw[15];

    wire [3:0]  speed = 4'd1 << sw[4:3];          // 1, 2, 4, 8
    wire [9:0]  rstep = {6'd0, speed};            // angle units per frame
    wire signed [15:0] mstep = $signed({11'd0, speed, 1'b0});   // 2..16  (Q8.8)
    wire signed [15:0] zstep = $signed({10'd0, speed, 2'b0});   // 4..32  (Q8.8)

    // ---------------- accelerometer: clamp, map axes, low-pass ---------------
    function signed [11:0] clamp1g;
        input signed [11:0] a;
        begin
            clamp1g = (a > 12'sd1000) ? 12'sd1000 : (a < -12'sd1000) ? -12'sd1000 : a;
        end
    endfunction
    wire signed [11:0] ax0 = clamp1g(sw[12] ? acc_y : acc_x);
    wire signed [11:0] ay0 = clamp1g(sw[12] ? acc_x : acc_y);
    wire signed [11:0] ax1 = sw[13] ? -ax0 : ax0;
    wire signed [11:0] ay1 = sw[14] ? -ay0 : ay0;

    reg signed [13:0] fx, fy;                     // filtered, same scale (mg)
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            fx <= 14'sd0; fy <= 14'sd0;
        end else if (acc_valid) begin             // f += (a - f) / 4
            fx <= fx + (($signed({{2{ax1[11]}}, ax1}) - fx) >>> 2);
            fy <= fy + (($signed({{2{ay1[11]}}, ay1}) - fy) >>> 2);
        end
    end
    // mg -> angle units: 1024 / (2*pi*1000) ~= 167/1024 (+/-1 g -> +/-163 = +/-57 deg)
    wire signed [25:0] tp_mul = fy * 12'sd167;
    wire signed [25:0] tr_mul = fx * 12'sd167;
    wire signed [9:0]  tp_ang = tp_mul >>> 10;
    wire signed [9:0]  tr_ang = tr_mul >>> 10;

    // ---------------- move limits (GENERATED by tools/gen_move_limits.py) ------
    // The cube's bounding sphere (radius 1.76) must stay inside the 60-degree
    // view at the current zoom distance, so no vertex ever leaves the 300x400
    // screen (triangle_setup would clamp it and bend the face).
    // index k = (cam_dist - 4.5) / 0.25, entry = limit for the NEAREST distance in
    // that step (always on the safe side). Q8.8 world units.
    // |tx| limit
    function signed [15:0] lim_x;
        input [4:0] k;
        begin
            case (k)
                5'd0: lim_x = 16'sd7;
                5'd1: lim_x = 16'sd35;
                5'd2: lim_x = 16'sd62;
                5'd3: lim_x = 16'sd89;
                5'd4: lim_x = 16'sd117;
                5'd5: lim_x = 16'sd144;
                5'd6: lim_x = 16'sd171;
                5'd7: lim_x = 16'sd198;
                5'd8: lim_x = 16'sd225;
                5'd9: lim_x = 16'sd252;
                5'd10: lim_x = 16'sd279;
                5'd11: lim_x = 16'sd306;
                5'd12: lim_x = 16'sd333;
                5'd13: lim_x = 16'sd360;
                5'd14: lim_x = 16'sd387;
                5'd15: lim_x = 16'sd414;
                5'd16: lim_x = 16'sd441;
                5'd17: lim_x = 16'sd468;
                5'd18: lim_x = 16'sd495;
                5'd19: lim_x = 16'sd522;
                5'd20: lim_x = 16'sd549;
                5'd21: lim_x = 16'sd576;
                5'd22: lim_x = 16'sd604;
                5'd23: lim_x = 16'sd631;
                5'd24: lim_x = 16'sd658;
                5'd25: lim_x = 16'sd685;
                5'd26: lim_x = 16'sd712;
                5'd27: lim_x = 16'sd740;
                5'd28: lim_x = 16'sd767;
                5'd29: lim_x = 16'sd794;
                5'd30: lim_x = 16'sd821;
                5'd31: lim_x = 16'sd821;
                default: lim_x = 16'sd0;
            endcase
        end
    endfunction
    // |ty| limit
    function signed [15:0] lim_y;
        input [4:0] k;
        begin
            case (k)
                5'd0: lim_y = 16'sd140;
                5'd1: lim_y = 16'sd176;
                5'd2: lim_y = 16'sd211;
                5'd3: lim_y = 16'sd246;
                5'd4: lim_y = 16'sd282;
                5'd5: lim_y = 16'sd317;
                5'd6: lim_y = 16'sd352;
                5'd7: lim_y = 16'sd388;
                5'd8: lim_y = 16'sd423;
                5'd9: lim_y = 16'sd459;
                5'd10: lim_y = 16'sd494;
                5'd11: lim_y = 16'sd530;
                5'd12: lim_y = 16'sd566;
                5'd13: lim_y = 16'sd601;
                5'd14: lim_y = 16'sd637;
                5'd15: lim_y = 16'sd673;
                5'd16: lim_y = 16'sd709;
                5'd17: lim_y = 16'sd744;
                5'd18: lim_y = 16'sd780;
                5'd19: lim_y = 16'sd816;
                5'd20: lim_y = 16'sd852;
                5'd21: lim_y = 16'sd888;
                5'd22: lim_y = 16'sd924;
                5'd23: lim_y = 16'sd960;
                5'd24: lim_y = 16'sd997;
                5'd25: lim_y = 16'sd1033;
                5'd26: lim_y = 16'sd1069;
                5'd27: lim_y = 16'sd1105;
                5'd28: lim_y = 16'sd1141;
                5'd29: lim_y = 16'sd1177;
                5'd30: lim_y = 16'sd1214;
                5'd31: lim_y = 16'sd1214;
                default: lim_y = 16'sd0;
            endcase
        end
    endfunction

    // ---------------- per-frame update ---------------------------------------
    reg signed [16:0] nx, ny, nd;                 // one extra bit for clamping
    reg               lim;
    reg signed [15:0] lx, ly;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            yaw <= YAW0; pitch <= PITCH0; pitch_eff <= PITCH0; roll_eff <= 10'd0;
            tx <= 16'sd0; ty <= 16'sd0; cam_dist <= DIST0; at_limit <= 1'b0;
            tilt_pitch <= 10'sd0; tilt_roll <= 10'sd0;
        end else if (tick) begin
            tilt_pitch <= tp_ang;
            tilt_roll  <= tr_ang;
            if (btn_c) begin
                yaw <= YAW0; pitch <= PITCH0; tx <= 16'sd0; ty <= 16'sd0;
                cam_dist <= DIST0; at_limit <= 1'b0;
                pitch_eff <= PITCH0 + (tilt_on ? tp_ang : 10'sd0);
                roll_eff  <= tilt_on ? tr_ang : 10'd0;
            end else begin
                // ---- yaw: auto-spin + left/right (not in move mode) ----
                yaw <= yaw + (auto_spin ? rstep : 10'd0)
                           + ((!move_mode && btn_r) ? rstep : 10'd0)
                           - ((!move_mode && btn_l) ? rstep : 10'd0);
                // ---- pitch: up/down in rotate mode (up = front face moves up) ----
                if (!move_mode && !zoom_mode)
                    pitch <= pitch - (btn_u ? rstep : 10'd0) + (btn_d ? rstep : 10'd0);
                pitch_eff <= ((!move_mode && !zoom_mode)
                                 ? (pitch - (btn_u ? rstep : 10'd0) + (btn_d ? rstep : 10'd0))
                                 : pitch)
                             + (tilt_on ? tp_ang : 10'sd0);
                roll_eff  <= tilt_on ? tr_ang : 10'd0;

                // ---- move ----
                nx = {tx[15], tx} + ((move_mode && btn_r) ? mstep : 16'sd0)
                                  - ((move_mode && btn_l) ? mstep : 16'sd0);
                ny = {ty[15], ty} + ((move_mode && btn_u) ? mstep : 16'sd0)
                                  - ((move_mode && btn_d) ? mstep : 16'sd0);
                // ---- zoom ----
                nd = {cam_dist[15], cam_dist} - ((zoom_mode && btn_u) ? zstep : 16'sd0)
                                              + ((zoom_mode && btn_d) ? zstep : 16'sd0);
                lim = 1'b0;
                if (nd <  DIST_MIN) begin nd =  DIST_MIN; lim = 1'b1; end
                if (nd >  DIST_MAX) begin nd =  DIST_MAX; lim = 1'b1; end
                // move limits for the NEW distance (zooming in pulls the cube inward)
                lx = lim_x(nd[11:6] - DIST_MIN[11:6]);
                ly = lim_y(nd[11:6] - DIST_MIN[11:6]);
                if (nx >  lx) begin nx =  lx; lim = lim | (move_mode && btn_r); end
                if (nx < -lx) begin nx = -lx; lim = lim | (move_mode && btn_l); end
                if (ny >  ly) begin ny =  ly; lim = lim | (move_mode && btn_u); end
                if (ny < -ly) begin ny = -ly; lim = lim | (move_mode && btn_d); end
                tx <= nx[15:0]; ty <= ny[15:0]; cam_dist <= nd[15:0];
                at_limit <= lim;
            end
        end
    end
endmodule
