    localparam signed [15:0] K_FX = 16'sd9459;    // 2.309401 * 4096
    localparam signed [15:0] K_FY = 16'sd7094;    // 1.732051 * 4096
    localparam signed [15:0] K_A  = -16'sd9557;   // -2.333333 * 4096
    localparam signed [31:0] B_Q8 = -32'sd3413;   // -13.333333 * 256

    // round-half-up arithmetic right shift
    function signed [31:0] rsh;
        input signed [47:0] x;
        input integer       n;
        begin
            rsh = (x + (48'sd1 <<< (n-1))) >>> n;
        end
    endfunction

