//   clip      X = FX*eye_x          FX = 2.309401 (60 deg vertical FOV, 300/400 aspect)
//             Y = FY*eye_y          FY = 1.732051
//             Z = A*eye_z + B       A  = -7/3, B = -40/3   (near 4, far 10)
//             W = -eye_z
//   These are exactly the camera constants of the project's matrix.mem
//   (that file = yaw 35 deg, pitch 25 deg, cam_dist 6, no move).
//
