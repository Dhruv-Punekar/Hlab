    function signed [15:0] sin_q14;
        input [9:0] a;
        reg [14:0] m;
        begin
            m = a[8] ? qsin(9'd256 - {1'b0, a[7:0]}) : qsin({1'b0, a[7:0]});
            sin_q14 = a[9] ? -$signed({1'b0, m}) : $signed({1'b0, m});
        end
    endfunction

    function signed [15:0] cos_q14;
        input [9:0] a;
        begin
            cos_q14 = sin_q14(a + 10'd256);
        end
    endfunction


