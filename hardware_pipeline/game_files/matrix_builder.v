        sb <= sin_q14(yaw);    cb <= cos_q14(yaw);
        sc <= sin_q14(roll);   cc <= cos_q14(roll);
        t1_tx <= tx; t1_ty <= ty; t1_d <= cam_dist;

        // stage 2
        p1 <= rsh(sa * sb, 14);
        p2 <= rsh(sa * cb, 14);
        p3 <= rsh(ca * sb, 14);
        p4 <= rsh(ca * cb, 14);
        s2_sa <= sa; s2_ca <= ca; s2_sb <= sb; s2_cb <= cb; s2_sc <= sc; s2_cc <= cc;
        t2_tx <= t1_tx; t2_ty <= t1_ty; t2_d <= t1_d;

        // stage 3
        q00a <= s2_cc * s2_cb;   q00b <= s2_sc * p1;
        q01  <= s2_sc * s2_ca;
        q02a <= s2_cc * s2_sb;   q02b <= s2_sc * p2;
        q10a <= s2_sc * s2_cb;   q10b <= s2_cc * p1;
        q11  <= s2_cc * s2_ca;
        q12a <= s2_sc * s2_sb;   q12b <= s2_cc * p2;
        s3_r20 <= -p3;  s3_r21 <= s2_sa;  s3_r22 <= p4;
        t3_tx <= t2_tx; t3_ty <= t2_ty; t3_d <= t2_d;

        // stage 4: R = Rz * Rx * Ry
        r00 <= rsh(q00a - q00b, 14);
        r01 <= rsh(-q01, 14);
        r02 <= rsh(q02a + q02b, 14);
        r10 <= rsh(q10a + q10b, 14);
        r11 <= rsh(q11, 14);
        r12 <= rsh(q12a - q12b, 14);
        r20 <= s3_r20;  r21 <= s3_r21;  r22 <= s3_r22;
        t4_tx <= t3_tx; t4_ty <= t3_ty; t4_d <= t3_d;

        // stage 5: projection scale -> Q24.8   (Q1.14 * Q.12 >> 18 = Q.8)
        m00 <= rsh(r00 * K_FX, 18);  m01 <= rsh(r01 * K_FX, 18);  m02 <= rsh(r02 * K_FX, 18);
        m10 <= rsh(r10 * K_FY, 18);  m11 <= rsh(r11 * K_FY, 18);  m12 <= rsh(r12 * K_FY, 18);
        m20 <= rsh(r20 * K_A,  18);  m21 <= rsh(r21 * K_A,  18);  m22 <= rsh(r22 * K_A,  18);
        m30 <= rsh(-r20, 6);         m31 <= rsh(-r21, 6);         m32 <= rsh(-r22, 6);
        m03 <= rsh(t4_tx * K_FX, 12);
        m13 <= rsh(t4_ty * K_FY, 12);
        m23 <= rsh(t4_d * -K_A, 12) + B_Q8;     // -A*cam_dist + B
        m33 <= t4_d;

        done <= vld[4];
    end

    // matrix_regs[k] holds element e = 15-k (e = row*4 + col): M33 first ... M00 last
    reg [31:0] word;
    always @* begin
        case (rd_addr)
            4'd15: word = m00;  4'd14: word = m01;  4'd13: word = m02;  4'd12: word = m03;
            4'd11: word = m10;  4'd10: word = m11;  4'd9:  word = m12;  4'd8:  word = m13;
            4'd7:  word = m20;  4'd6:  word = m21;  4'd5:  word = m22;  4'd4:  word = m23;
            4'd3:  word = m30;  4'd2:  word = m31;  4'd1:  word = m32;  default: word = m33;
        endcase
    end
    assign rd_data = word;

    initial vld = 6'd0;
endmodule
