`timescale 1ns / 1ps

// ============================================================================
// Module: matrix_memory
// Purpose: Stores the 4x4 Transformation Matrix.
// Implementation: Uses a Register Array instead of BRAM.
// Why? BRAMs usually only have 1 or 2 read ports. The Transform Engine needs
// ALL 16 values at the exact same time to do 16 parallel multiplications.
// Therefore, we flatten the memory into a massive 512-bit output wire.
// ============================================================================
module matrix_memory (
    input wire clk,
    input wire we,                   // Write enable (from future UART Receiver)
    input wire [3:0] write_addr,     // Address 0 to 15 (which matrix element to update)
    input wire [31:0] write_data,    // Q24.8 data from UART

    // 512-bit flattened output containing all 16 matrix elements (16 * 32 = 512)
    output wire [512-1:0] matrix_out
);

    // Create 16 individual 32-bit registers
    reg [31:0] matrix_regs [0:15];

    // ========================================================================
    // INITIALIZATION
    // ========================================================================
    // Read the identity matrix generated by the Python script
    initial begin
        $readmemh("matrix.hex", matrix_regs);
    end

    // ========================================================================
    // WRITE PORT (For Future Real-Time Updates)
    // ========================================================================
    always @(posedge clk) begin
        if (we) begin
            matrix_regs[write_addr] <= write_data;
        end
    end

    // ========================================================================
    // COMBINATIONAL FLATTENING
    // ========================================================================
    // This loop connects the 16 separate 32-bit registers into one giant 512-bit bus.
    // It takes 0 clock cycles (it is pure wiring).
    genvar i;
    generate
        for (i = 0; i < 16; i = i + 1) begin : flatten_matrix
            assign matrix_out[(i * 32) +: 32] = matrix_regs[i];
        end
    endgenerate

endmodule
